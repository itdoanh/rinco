// Package tracking provides a tiny 1x1 transparent GIF generator and a
// click redirector used by the email service.
package tracking

import (
	"encoding/base64"
)

// PixelGif is the canonical 43-byte transparent 1x1 GIF used by tracking
// pixels.  Encoding it inline avoids any file-system dependency.
var PixelGif = []byte{
	0x47, 0x49, 0x46, 0x38, 0x39, 0x61, 0x01, 0x00, 0x01, 0x00,
	0x80, 0x00, 0x00, 0xff, 0xff, 0xff, 0x00, 0x00, 0x00, 0x21,
	0xf9, 0x04, 0x01, 0x00, 0x00, 0x00, 0x00, 0x2c, 0x00, 0x00,
	0x00, 0x00, 0x01, 0x00, 0x01, 0x00, 0x00, 0x02, 0x02, 0x44,
	0x01, 0x00, 0x3b,
}

// PixelBase64 is the base64-encoded form of the GIF, useful when emitting
// inline pixels (data: URIs).
var PixelBase64 = base64.StdEncoding.EncodeToString(PixelGif)